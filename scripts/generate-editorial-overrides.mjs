import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const draftDirectory = join(projectRoot, "output", "today2424", "drafts");
const outputPath = join(projectRoot, "data", "editorial-overrides.ts");

const draftFiles = readdirSync(draftDirectory)
  .filter((fileName) => fileName.endsWith(".mdx"))
  .sort((left, right) => left.localeCompare(right));

const overrides = {};

for (const fileName of draftFiles) {
  const source = readFileSync(join(draftDirectory, fileName), "utf8");
  const { fields, body } = parseDraft(source);
  const slug = fields.slug ?? fileName.replace(/\.mdx$/, "");
  const title = fields.title;

  if (!title) {
    throw new Error(`Missing title in ${fileName}`);
  }

  overrides[slug] = {
    title,
    excerpt: fields.description ?? fields.subtitle ?? deriveExcerpt(body),
    content: markdownToHtml(body),
  };
}

const output = `// Generated by scripts/generate-editorial-overrides.mjs. Do not edit by hand.\n\nexport type EditorialOverride = {\n  title: string;\n  excerpt: string;\n  content: string;\n};\n\nexport const editorialOverrides: Record<string, EditorialOverride> = ${JSON.stringify(overrides, null, 2)};\n`;

writeFileSync(outputPath, output, "utf8");
console.log(`generated ${draftFiles.length} editorial overrides at ${outputPath}`);

function parseDraft(source) {
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!match) {
    return { fields: {}, body: source };
  }

  const fields = {};
  for (const line of match[1].split(/\r?\n/)) {
    const field = line.match(/^([A-Za-z][A-Za-z0-9_-]*):\s*(.*)$/);
    if (!field) continue;
    fields[field[1]] = parseScalar(field[2]);
  }

  return { fields, body: match[2].trim() };
}

function parseScalar(value) {
  const trimmed = value.trim();
  if ((trimmed.startsWith('"') && trimmed.endsWith('"')) || (trimmed.startsWith("'") && trimmed.endsWith("'"))) {
    try {
      return JSON.parse(trimmed);
    } catch {
      return trimmed.slice(1, -1);
    }
  }
  return trimmed;
}

function deriveExcerpt(body) {
  const firstParagraph = body
    .split(/\r?\n\s*\r?\n/)
    .map((paragraph) => paragraph.replace(/^>\s*/, "").trim())
    .find((paragraph) => paragraph && !paragraph.startsWith("#") && !paragraph.startsWith("|"));

  return (firstParagraph ?? "").replace(/[*_`]/g, "").slice(0, 147).trimEnd() + "...";
}

function markdownToHtml(body) {
  const lines = body.replace(/\r/g, "").split("\n");
  const chunks = [];
  let paragraph = [];
  let list = null;
  let table = [];
  let quote = [];

  const flushParagraph = () => {
    if (paragraph.length === 0) return;
    const text = paragraph.join(" ").trim();
    if (text) chunks.push(`<p>${inline(text)}</p>`);
    paragraph = [];
  };

  const flushList = () => {
    if (!list) return;
    chunks.push(`<${list.type}>${list.items.map((item) => `<li>${inline(item)}</li>`).join("")}</${list.type}>`);
    list = null;
  };

  const flushTable = () => {
    if (table.length === 0) return;
    chunks.push(tableToHtml(table));
    table = [];
  };

  const flushQuote = () => {
    if (quote.length === 0) return;
    chunks.push(`<blockquote><p>${inline(quote.join(" "))}</p></blockquote>`);
    quote = [];
  };

  const flushBlocks = () => {
    flushParagraph();
    flushList();
    flushTable();
    flushQuote();
  };

  for (const line of lines) {
    const trimmed = line.trim();
    const heading = line.match(/^(#{1,6})\s+(.+)$/);
    const unordered = line.match(/^\s*[-*]\s+(.+)$/);
    const ordered = line.match(/^\s*\d+[.)]\s+(.+)$/);
    const blockquote = line.match(/^\s*>\s?(.*)$/);
    const isTableRow = /^\s*\|.*\|\s*$/.test(line);

    if (!trimmed) {
      flushBlocks();
      continue;
    }

    if (heading) {
      flushBlocks();
      const level = Number(heading[1].length);
      if (level > 1) chunks.push(`<h${Math.min(level, 6)}>${inline(heading[2])}</h${Math.min(level, 6)}>`);
      continue;
    }

    if (isTableRow) {
      flushParagraph();
      flushList();
      flushQuote();
      table.push(trimmed);
      continue;
    }

    if (unordered || ordered) {
      flushParagraph();
      flushTable();
      flushQuote();
      const type = unordered ? "ul" : "ol";
      if (!list || list.type !== type) {
        flushList();
        list = { type, items: [] };
      }
      list.items.push((unordered ?? ordered)[1]);
      continue;
    }

    if (blockquote) {
      flushParagraph();
      flushList();
      flushTable();
      quote.push(blockquote[1]);
      continue;
    }

    if (/^\s*[-*_]{3,}\s*$/.test(line)) {
      flushBlocks();
      chunks.push("<hr />");
      continue;
    }

    flushList();
    flushTable();
    flushQuote();
    paragraph.push(trimmed);
  }

  flushBlocks();
  return `<article class="editorial-prose">${chunks.join("\n")}</article>`;
}

function tableToHtml(rows) {
  const cells = rows
    .map((row) => row.replace(/^\|/, "").replace(/\|$/, "").split("|").map((cell) => cell.trim()))
    .filter((row) => row.length > 0);

  if (cells.length === 0) return "";
  const header = cells[0];
  const body = cells.slice(1).filter((row) => !row.every((cell) => /^:?-{3,}:?$/.test(cell)));
  return [
    '<div class="overflow-x-auto"><table>',
    `<thead><tr>${header.map((cell) => `<th>${inline(cell)}</th>`).join("")}</tr></thead>`,
    body.length > 0 ? `<tbody>${body.map((row) => `<tr>${row.map((cell) => `<td>${inline(cell)}</td>`).join("")}</tr>`).join("")}</tbody>` : "",
    "</table></div>",
  ].join("");
}

function inline(value) {
  const escaped = escapeHtml(value);
  return escaped
    .replace(/\[([^\]]+)\]\(((?:https?:\/\/|\/)[^\s)]+)\)/g, '<a href="$2">$1</a>')
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
    .replace(/__([^_]+)__/g, "<strong>$1</strong>")
    .replace(/`([^`]+)`/g, "<code>$1</code>")
    .replace(/\*([^*]+)\*/g, "<em>$1</em>")
    .replace(/_([^_]+)_/g, "<em>$1</em>");
}

function escapeHtml(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}
